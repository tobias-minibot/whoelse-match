const STAMP = "2026-09-12T12:00:00.000Z";

function listing(partial) {
  const currency = partial.currency;
  const symbol = currency === "EUR" ? "€" : "$";
  const beds =
    partial.bedrooms === 0 ? "studio" : `${partial.bedrooms}-bedroom`;
  const kind = partial.listingKind;
  const kindPhrase =
    kind === "sublet" ? "furnished sublet" : kind === "room" ? "room" : "apartment";
  const pet = partial.pets ? "pets allowed" : "no pets";
  const furn = partial.furnished ? "furnished" : "unfurnished";
  const window = partial.availableTo
    ? `${partial.availableFrom} to ${partial.availableTo}`
    : `from ${partial.availableFrom}`;
  return {
    id: partial.id,
    type: "resource",
    name: partial.name,
    description: `DEMO synthetic listing — not a real apartment. ${beds} ${kindPhrase} in ${partial.neighborhood}, ${partial.city}. ${symbol}${partial.rent}/${partial.term ?? "mo"}, ${furn}, ${pet}. Available ${window}.`,
    offers: unique([
      "apartment",
      kindPhrase,
      beds,
      `${beds} apartment`,
      furn,
      pet,
      `housing listing`,
      `${kind} in ${partial.neighborhood}`,
      `place near ${partial.neighborhood}`,
      `${partial.city} ${kindPhrase}`,
      ...(partial.extraOffers ?? []),
    ]),
    seeks: ["tenant", "renter", "good tenant"],
    capabilities: ["housing listing"],
    attributes: {
      role: "listing",
      listingKind: kind,
      bedrooms: partial.bedrooms,
      rent: partial.rent,
      currency,
      furnished: partial.furnished,
      pets: partial.pets,
      availableFrom: partial.availableFrom,
      availableTo: partial.availableTo ?? null,
      durationMonths: partial.durationMonths ?? null,
      neighborhood: partial.neighborhood,
      amenities: partial.amenities ?? [],
      synthetic: true,
    },
    preferences: {},
    availability: partial.availability ?? (partial.availableFrom <= "2026-10-31" ? "available next month" : "listed"),
    location: { city: partial.city, region: partial.region, country: partial.country },
    metadata: {
      demo: true,
      demoLabel: "DEMO synthetic listing — not a real apartment",
      vertical: "apartment",
    },
    trust: {
      status: "stub",
      provenance: "synthetic",
      notes: "synthetic demo listing — not scraped, not bookable",
    },
    provenance: "synthetic",
    created_at: STAMP,
  };
}

function seeker(partial) {
  const currency = partial.currency;
  const symbol = currency === "EUR" ? "€" : "$";
  const beds =
    partial.bedrooms === 0 ? "studio" : `${partial.bedrooms}-bedroom`;
  const furn = partial.furnished ? "furnished" : "unfurnished-ok";
  const pet = partial.pets ? "needs pet-friendly" : "no pets";
  return {
    id: partial.id,
    type: "human",
    name: partial.name,
    description: `DEMO synthetic seeker — not a real person, not a dating profile. Looking for a ${furn} ${beds} in ${partial.neighborhood ? `${partial.neighborhood}, ` : ""}${partial.city}. Budget ${symbol}${partial.budget}. ${pet}.`,
    offers: unique([
      "tenant",
      "good tenant",
      "renter",
      ...(partial.extraOffers ?? []),
    ]),
    seeks: unique([
      `${furn} apartment`,
      `${beds} apartment`,
      `apartment in ${partial.city}`,
      partial.furnished ? `furnished apartment in ${partial.city}` : `apartment in ${partial.city}`,
      partial.listingKind === "sublet" ? "3-month sublet" : `${partial.listingKind ?? "rent"}`,
      ...(partial.extraSeeks ?? []),
    ]),
    capabilities: ["tenant"],
    attributes: {
      role: "seeker",
      listingKind: partial.listingKind ?? "rent",
      bedrooms: partial.bedrooms,
      budget: partial.budget,
      rent: partial.budget,
      currency,
      furnished: partial.furnished,
      pets: partial.pets,
      availableFrom: partial.availableFrom ?? "2026-10-01",
      availableTo: partial.availableTo ?? null,
      durationMonths: partial.durationMonths ?? null,
      neighborhood: partial.neighborhood ?? "",
      occupation: partial.occupation ?? "renter",
      synthetic: true,
    },
    preferences: {},
    availability: partial.availability ?? "moving next month",
    location: { city: partial.city, region: partial.region, country: partial.country },
    metadata: {
      demo: true,
      demoLabel: "DEMO synthetic seeker — not a real person",
      vertical: "apartment",
    },
    trust: {
      status: "stub",
      provenance: "synthetic",
      notes: "synthetic seeker — not a dating profile",
    },
    provenance: "synthetic",
    created_at: STAMP,
  };
}

function unique(values) {
  return [...new Set(values.filter(Boolean))];
}

